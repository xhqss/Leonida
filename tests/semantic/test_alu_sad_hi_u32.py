            # Oracle computation
            lo, hi, full = ref_sad_full_64(s0, s1, s2)

            # Invariant 1: Carry in {0, 1}
            self.assertIn(hi, (0, 1))

            # Invariant 2: 64-bit reconstruction
            self.assertEqual((hi << 32) | lo, full)

